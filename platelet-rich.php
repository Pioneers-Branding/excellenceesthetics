            <h5>Procedure</h5>
            <p>The following steps are involved in PRP injections:</p>
            <ul>
                <li>Doctor draws blood from a vein in the arm.
                <li>They place the blood sample in a centrifuge.
                <li>The centrifuge spins the blood, separating its components to separate the platelet-rich plasma from the blood.
                <li>Doctor extracts the platelets using a syringe and injects the platelets into targeted areas of the scalp or body.
                <li>A numbing cream is applied to the area of the body where the PRP injections will be used, making the PRP process pain-free.

            </ul>
            
