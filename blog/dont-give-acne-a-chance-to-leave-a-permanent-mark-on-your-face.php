                                    <h2>Don't give Acne a chance to leave a permanent mark on your face. Get an effective solution.</h2>
                                    <h4>Don't let acne scar affect your confidence</h4>
                                    <p>Acne almost hits everyone, but what is harder to deal with are the scars it leaves behind. Acne scars are rigid to let go, and as the skin ages, the scars become more visible as the skin loses collagen.</p>
                                    <h4>What is Acne Scar and why do they occur?</h4>
                                    <p>The skin is the largest organ and is made up of many glands. Acne mostly occurs on the part of the skin where sebaceous glands are present in large numbers. Sebaceous glands are oil-producing glands that are mostly present in facial tissues, back, and neck.</p>
                                    <p>Acne Scars occur when the acne blemishes get inflamed by irritants and as a result, the acne pore swells and due to the damage to the dermal tissues leads to scars.</p>
                                    <h4>Why can't scars heal on their own?</h4>
                                    <p>The scars can take two forms either they occur beneath the skin surface, known as depressed scars or it develops on the surface of the skin. Some Scars heal quickly while some spread to other tissues as well. That is why some kinds of scars can only get healed with proper treatment and care.</p>
                                    <h4>How can you get rid of Acne Scars?</h4>
                                    <p>Now, numerous treatments guarantee to remove scars but it depends on the type of scars and the nature of your skin.</p>
                                    <div class="entry-content">
                                        <ul>
                                            <li><b>Home Skin Care:</b> 
                                                <p>First comes the home skincare. Having a good skin routine can also prevent acne and acne scars. Sunscreens can help and create a layer between the pores and the irritants. One can also use over-the-counter medicated creams containing hydroxyl acids or azelaic acid. If the problem does not heal or you face any irritation on the skin, consult your dermatologist.</p>
                                            </li>
                                            <li><b>Laser Treatment:</b> 
                                                <p>Laser Treatment is the most emerging and likable treatment option to get rid of acne scars. A laser can treat mild and moderate acne scars. The laser removes the first layer of the skin around the scars and tightens the middle layer of the skin. This results in smoother skin. This is done by a dermatologist and it is a non-invasive procedure. The procedure take usually between half an hour to two hours depending on your skin type and the depth of the scars.</p>
                                                <p>The doctor applies a numbing cream before the procedure to have a smooth and painless experience.</p>
                                                <p>Many people think laser treatment can have serious consequences for the skin; however, the technology being used nowadays offers a smooth and painless experience without any side effects. No matter what your skin type or whether you have darker skin, the laser treatment works effectively to treat acne scars.</p>
                                            </li>
                                            <li><b>Chemical Peel:</b> 
                                                <p>Chemical peels work by removing the top layer of the skin and allowing new skin to appear. It is done by applying a chemical mask on the skin and then removing the top layer of the skin. This procedure lightens the scar. A chemical peel works best for raised scars rather than depressed scars. Chemical peels smoothen the texture and the tone, it lightens the dark spots and unclogs the pores.</p>    
                                            </li>
                                            <li><b>Microdermabrasion:</b>
                                                <p>In this process, the dead cells are removed from the skin, and the top layer is removed from a handheld rolling device. The scars may be completely removed or appear less visible. This process should be done by a certified and experienced dermatologist as the wrong procedure can lead to redness, itching, and other problems with the skin.</p>
                                            </li>
                                            <li><b>Subcision and threads:</b>
                                                <p>Subcision is a procedure which releases scars that have become stuck to the deeper tissues and bound down. When a scar forms, new collagen is produced. Subcision helps to improve any condition in which the skin is being pulled downwards by scar tissue.</p>
                                            </li>
                                        </ul>
