                            <li>Fine lines & wrinkles</li>
                            <li>Stretch marks</li>
                            <li>Post-traumatic scars</li>
                            <li>Skin laxity (jawline, under-eye, neck)</li>
                            <li>Vaginal tightening and rejuvenation</li>
                        </ul>

                        <h5>Key Features & Benefits</h5>
                        <ul>
                            <li><b>Safe & precise:</b> Adjustable needle depth for customized treatment</li>
                            <li><b>Targeted treatment:</b> Focuses energy in deeper layers without harming the top
