                        <h5>How Does Cellina PR MNRF Work?</h5>
                        <p><strong>Dual-Action Technology:</strong></p>
                        <ul>
                            <li><b>Microneedling RF:</b> Delivers thermal energy deep into the dermis via insulated
                                microneedles to stimulate collagen production and skin tightening.</li>
                            <li><b>Fractional RF (Matrix Mode):</b> Gently heats the surface layer of skin to improve
                                tone, texture, and pigmentation.</li>
                        </ul>
                        <p>Together, these modes provide superficial and deep-level rejuvenation—all in one session,
                            with minimal downtime.</p>

