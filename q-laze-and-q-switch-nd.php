                        <h5> What is Q-Laze+ Q-Switch Nd:YAG Laser?</h5>
                        <p>Q-Laze+ is a premium Q-switched Nd:YAG laser device that delivers short, high-intensity
                            pulses of laser energy into the skin. This energy breaks down unwanted pigment, tattoo ink,
                            or damaged cells while leaving the surrounding skin unharmed.</p>
                        <p><strong>It's ideal for treating:</strong></p>
                        <ul>
                            <li>Pigmentation disorders</li>
                            <li>Acne marks</li>
                            <li>Sun damage</li>
                            <li>Melasma</li>
                            <li>Unwanted tattoos</li>
                            <li>Skin dullness and uneven tone</li>
                        </ul>

                        <h5> How Q-Switch Laser Works</h5>
                        <p>Q-switched lasers use a powerful beam that shatters pigment particles into tiny fragments.
                            These are then naturally removed by your body's immune system. Q-Laze+ has both 1064 nm and
                            532 nm wavelengths:</p>
                        <ul>
                            <li><b>1064 nm:</b> Deep pigmentation, melasma, dermal pigmentation</li>
                            <li><b>532 nm:</b> Superficial pigmentation, sun spots, freckles, red tattoos</li>
                        </ul>
                        <p>Thanks to its non-ablative nature, there's no burning or peeling, and treatments are quick,
                            safe, and virtually painless.</p>

                        <h5>Benefits of Q-Laze+ at Excellence Esthetics</h5>
                        <ul>
                            <li> Non-invasive, no downtime treatment</li>
                            <li> Suitable for all skin types, including Indian skin</li>
                            <li> Effective on both superficial and deep pigmentation</li>
                            <li> Approved technology for safe, repeatable sessions</li>
                            <li> Also improves skin clarity, glow, and texture</li>
                        </ul>

                        <h5> What Can Q-Laze+ Treat?</h5>
                        <ul>
                            <li>Melasma and hyperpigmentation</li>
                            <li>Freckles and lentigines (age spots)</li>
                            <li>Post-acne pigmentation</li>
                            <li>Uneven skin tone or tanning</li>
                            <li>Dull skin needing brightening (Laser Toning)</li>
                            <li>Tattoo removal (black, red, blue ink tattoos)</li>
                            <li>Hollywood Carbon peel</li>
                            <li>Under eye dark circles</li>
                            <li>Lip lightening</li>
                        </ul>

                        <h5> Treatment Details</h5>
                        <ul>
                            <li><b>Session time:</b> 15–30 minutes</li>
                            <li><b>Anesthesia:</b> Not usually needed (numbing cream optional for sensitive skin)</li>
                            <li><b>Downtime:</b> None to minimal (slight redness for a few hours)</li>
                            <li><b>Sessions required:</b> 4–6 sessions depending on concern</li>
                            <li><b>Results:</b> Progressive — pigmentation fades over weeks</li>
                        </ul>

