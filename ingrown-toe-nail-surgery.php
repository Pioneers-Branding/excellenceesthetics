            <p>Ingrown toenails are difficult to remove manually. Hence, surgical removal treatment of an ingrown toenail has become quite important and popular. Depending on your toenail, the procedure might involve removing a small portion of the affected nail or the complete toenail. The adjacent nail bed beneath this part is then destroyed. The nail is treated and reshaped in such a way that it does not tug into the skin anymore and can regrow properly.</p>
