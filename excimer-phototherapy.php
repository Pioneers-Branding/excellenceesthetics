                        <h4> Excimer Phototherapy in Gurgaon</h4>
                        <p><strong>Targeted Light Therapy for Vitiligo, Psoriasis & Atopic Dermatitis</strong></p>
                        <p>Now available at <strong>Excellence Esthetics, Gurgaon</strong> – Excimer Phototherapy, the
                            gold-standard in targeted UVB light treatment for chronic skin conditions like vitiligo,
                            psoriasis, and eczema (atopic dermatitis).</p>
                        <p>If you're looking for a safe, fast, and effective treatment with minimal side effects,
                            Excimer laser therapy may be the answer.</p>

                        <h5> What is Excimer Phototherapy?</h5>
                        <p>Excimer phototherapy uses <strong>308 nm monochromatic UVB light</strong> to treat specific
                            patches of affected skin. Unlike traditional UV light boxes, this targeted technology
                            focuses only on diseased skin — sparing the healthy surrounding tissue and delivering faster
                            results with fewer sessions.</p>

                        <h5> Benefits of Excimer Phototherapy</h5>
                        <ul>
                            <li> Targeted Treatment – No unnecessary UV exposure to healthy skin</li>
                            <li> Fast Results – Quicker response compared to full-body UV therapy</li>
                            <li> Safe for Children & Sensitive Areas</li>
                            <li> Minimal Side Effects – No systemic absorption, unlike oral medications</li>
                            <li> Painless & Non-invasive</li>
                            <li> Suitable for all skin types, including Indian skin tone</li>
                        </ul>

                        <h5> Conditions Treated with Excimer Therapy</h5>
                        <p>Excimer laser is particularly effective for autoimmune and inflammatory skin conditions,
                            including:</p>
                        <ul>
                            <li><b>Vitiligo</b> – Helps stimulate repigmentation by activating melanocytes</li>
                            <li><b>Psoriasis</b> – Clears stubborn plaques by reducing inflammation</li>
                            <li><b>Atopic Dermatitis (Eczema)</b> – Soothes itchy, inflamed skin</li>
                            <li><b>Alopecia Areata</b> – Can promote hair regrowth in patchy hair loss (off-label)</li>
                        </ul>

                        <h5> How Does It Work?</h5>
                        <p>Excimer emits a highly targeted beam of UVB light (308 nm), which:</p>
                        <ul>
                            <li>Suppresses the immune response in inflammatory skin conditions</li>
                            <li>Stimulates pigment-producing cells in vitiligo</li>
                            <li>Reduces skin cell turnover in psoriasis</li>
                            <li>Works precisely on lesions, sparing the surrounding skin</li>
                        </ul>
                        <p>Most patients begin to notice improvement within 4–6 sessions.</p>

                        <h5> Treatment Details</h5>
                        <ul>
                            <li><b>Session Duration:</b> 5–15 minutes</li>
                            <li><b>Frequency:</b> 1–3 sessions per week</li>
                            <li><b>Course Length:</b> Usually 10–20 sessions depending on the condition</li>
                            <li><b>Discomfort:</b> Minimal to none; no needles or anesthesia required</li>
                            <li><b>Downtime:</b> None — normal activities can resume immediately</li>
                        </ul>

