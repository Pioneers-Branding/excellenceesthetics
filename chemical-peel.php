            <h5>Types of Chemical Peeling</h5>
            <p>There are three basic types of chemical peels:</p>
            <ul>
                <li><b>Superficial or lunchtime peel:</b> Alpha-hydroxy acid or another mild acid is used to penetrate only the outer layer of skin to gently exfoliate it. The treatment is used to improve the appearance of mild skin discoloration and rough skin as well as to refresh the face, neck, chest, or hands.</li>
                <li><b>Medium peel: </b>Glycolic acid is applied to penetrate the out and middle layers of skin to remove damaged skin cells. The treatment is used to improve age spots, fine lines and wrinkles, freckles, and moderate skin discoloration.</li>
                <li><b>Deep peel:</b> Trichloroacetic acid or phenol is applied to deeply penetrate the middle layer of skin to remove damaged skin cells. The treatment removes moderate lines, age spots, freckles, and shallow scars. Patients will see a dramatic improvement in skin appearance.</li>
            </ul>
