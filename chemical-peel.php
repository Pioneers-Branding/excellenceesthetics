            <h5>Here are some of the peels we use:</h5>
            
            <p><b>Salicylic peel: </b>Chemical peel for oily, acne-prone skin and hyperkeratotic conditions. Salicylic Acid is mainly known for its keratolytic and comedolytic properties. The use of high concentrations of SA causes a white epidermolysis on papules, pustules, and comedones a few minutes after the application. The upper part of the pustule frequently breaks, allowing the acid to act from the epithelia of the follicle towards the sebaceous gland. It has the following properties: soothing, antipruritic, antiseptic, antimicrobial (reduces the population of propionibacterium acnes), astringent, anti-aging (accelerates the elimination of corneocytes), and anti-epidermoplastic. It is a safe peel without the risk of burn, as it evaporates rapidly and, after crystallization or once the product is dry, no further penetration of the active ingredients occurs.</p>
            <p><b>Glycolic peel: </b>Chemical peel for hyperpigmentation, inflammatory and non-inflammatory acne, and acne scars. Glycolic acid (GA) is one of the most commonly used chemical substances for superficial peels. This AHA causes total or partial changes in the epidermis and the papillary dermis. The procedure generates skin variations by stimulating epidermal proliferation, destroying specific layers of the altered skin, or inducing poorly known tissue inflammatory reactions. Skin changes can be seen after several applications of this type of peel, e.g, new collagen deposits and an increase of GAGs in the papillary dermis, which help repair sun-damaged skin.</p>
            <p><b>Yellow peel: </b>Treatment of the signs of aging, hyperpigmentation, and distension stretch marks on the skin. Retinol is a retinoid precursor of retinoic acid. It accelerates mitosis, increases enzymatic activity, and normalizes keratinization. It nourishes the skin, prevents the appearance of new wrinkles, reduces the depth of existing wrinkles, and increases the skin’s elasticity. Furthermore, retinol reduces blemishes caused by excessive exposure to UV radiation, regulating mobility and proliferation of melanocytes.</p>
            <p><b>Lactic peel: </b>It has a natural moisturizing effect by attracting water molecules to the stratum corneum and stimulating the synthesis of ceramides, improving and modulating the skin’s barrier function. It is known as a skin-lightening agent, as it induces homogeneous melanin dispersion. In addition, it has antioxidant effects and inhibits the action of tyrosinase, an enzyme involved in the first stages of melanogenesis.</p>
            <p><b>TCA:</b> Chemical peels for acne scars, deep pigmentation, wrinkles, xanthelasmas, and syringomas. Trichloroacetic acid removes skin that is aged, damaged, or deteriorated due to all types of organic or external processes. It causes skin proteins to coagulate, consequently destroying the epidermal layer that will be replaced by the new epidermis and connective tissue.</p>
            <p><b>Phenol peels: </b>Chemical peel aimed at keeping the thickness of the stratum corneum and stimulating dermo-epidermal cell turnover. Used for treatment of melasma, superficial and deep wrinkles, and acne scars.</p>
