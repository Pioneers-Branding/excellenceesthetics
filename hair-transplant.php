            <h5>We Use Follicle Unit Extraction(FUE) Technique</h5>
            <p>This is the most widely accepted and advanced technique for hair transplants in modern times. In this technique, individual hair follicles are selectively removed and transplanted to another portion of your body where hair is weaker or missing.</p>
            <p>The section from where the hair follicles are extracted is the donor area. Each hair follicle or graft is placed in the area of baldness or where the hair is thinning. The donor area should be dense with healthy hair. The extraction is done by micro punching with a special needle.</p>
            
