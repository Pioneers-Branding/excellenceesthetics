            <h5>What are Acne Scars?</h5>
            <p>Acne scars are the marks left behind by untreated acne breakouts. Acne scars can develop from cystic acne or from picking at your skin. These occur because of inflammation which damages the internal tissues. They often cause an irregular appearance of the skin and can be unflattering. Long after your acne is gone; your scars tend to become prominent and can affect your confidence.</p>
