            <p>Here at Excellence Esthetics, we use best available procedures for effective acne scar treatments. Dr Jitender Taneja examines your skin and determines the best method for your acne scar treatment. Micro-needling is a newer treatment that effectively helps in reducing the depth and diminishing the appearance of acne scars. We use two types of devices for microneedling treatment in Gurgaon- dermaroller and dermapen. Dermaroller is a small, hand-held, needle-studded roller which is used on the surface of the scars. The needles penetrate the numbed skin and as the skin heals, it makes collagen which treats the scars and tightens and smoothens the skin around.</p>
            <p>Dermapen is an advanced skin micro-needling system. The electronically powered multiple needles easily penetrate the skin or scar tissue to enhance and stimulate rejuvenation of the skin, while maintaining epidermal integrity and reducing downtime for the patient. The automatic vibrating function of the Dermapen increases the speed of the procedure and effectiveness, and provides absorption of medical grade products, with minimal discomfort. This treatment results in an increased production of collagen, elastin and hyaluronic acid which in turn improves your skin's appearance, texture and firmness. Besides, it also improves blood supply, which contributes to the overall glow of your skin. The effects of skin needling on acne scars are even better when the treatments are combined with vitamin C or PRP.</p>
            <p>Dermapen Microneedling is one of the most trusted facial skin treatments in the world today. It has been designed to provide more targeted results when compared to other microneedling treatments. The highly-controlled nature of Dermapen makes it medically safer than other forms of microneedling treatment. The microneedling tip of Dermapen comes in sterilized individual packs that are easily replaceable. This means that there are absolutely no chances of getting infected by others as the needles are replaced every time for a new patient. Also, the device can be personalized based on individual needs. The 11 stainless steel needles, which are loaded into the spring automated device can be adjusted from 0.25-2.50 mm, depending upon which area of your face needs treatment. This ensures that the punctures made by the needles are precise, effective, and safe.</p>
            <h5>The entire process of microneedling consists of four distinct stages.</h5>
            <h6><b>Stage 1 – Cleansing</b></h6>
            <p>First and foremost, the dead cells, dirt, and dust are removed through deep cleansing. This helps in the effective penetration of the needles into the skin for better treatment.</p>
            <h6><b>Stage 2 – Numbing cream Application</b></h6>
            <p>After skin cleansing, a topical numbing cream is applied for 30-45 minutes on the area that needs to be treated. Your skin becomes numb and there won’t be any discomfort during the procedure.</p>
            <h6><b>Stage 3 – Treatment</b></h6>
            <p>This is the stage where the microneedling process takes place, which has been explained above. As your skin is penetrated, it pumps and thickens, thereby reducing the appearance of those scars, fine lines, wrinkles, dark spots, etc.</p>
